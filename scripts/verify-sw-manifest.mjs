#!/usr/bin/env node
// Guards against a regression of a real bug found (and fixed) during
// development: Workbox's directoryIndex matching only rewrites the
// *trailing-slash* form of a URL to its index.html equivalent, but this
// site's clean URLs have no trailing slash (astro.config's
// trailingSlash: 'never'). build-sw.mjs's manifestTransforms renames each
// ".../index.html" precache entry to its clean-URL form to compensate -
// this script extracts the actual embedded manifest from the built
// dist/sw.js and asserts that rename actually took effect, rather than
// relying on someone remembering to manually re-test offline behavior
// with `fetch(url, {cache: 'only-if-cached'})` the way this was first
// caught.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SW_PATH = fileURLToPath(new URL('../dist/sw.js', import.meta.url));

function extractPrecacheManifest(swSource) {
  const marker = 'precacheAndRoute(';
  const start = swSource.indexOf(marker);
  if (start === -1) {
    throw new Error(`Could not find "${marker}" in dist/sw.js - was it actually generated by build-sw.mjs?`);
  }

  let depth = 0;
  let arrayStart = -1;
  for (let i = start + marker.length; i < swSource.length; i++) {
    const ch = swSource[i];
    if (ch === '[') {
      if (depth === 0) arrayStart = i;
      depth++;
    } else if (ch === ']') {
      depth--;
      if (depth === 0) {
        const arrayLiteral = swSource.slice(arrayStart, i + 1);
        // Safe to evaluate: this is our own build output, not user input.
        return new Function(`return ${arrayLiteral}`)();
      }
    }
  }
  throw new Error('precacheAndRoute(...) array was never closed - malformed dist/sw.js?');
}

const manifest = extractPrecacheManifest(readFileSync(SW_PATH, 'utf8'));
const urls = new Set(manifest.map((entry) => entry.url));

const errors = [];

// No nested ".../index.html" entry should survive the clean-URL rename.
// The one exception is bare root "index.html", which Workbox's built-in
// directoryIndex matching already handles correctly for a request to "/".
const leftoverIndexHtml = [...urls].filter((url) => url !== 'index.html' && url.endsWith('/index.html'));
if (leftoverIndexHtml.length > 0) {
  errors.push(
    `${leftoverIndexHtml.length} precache entries still end in "/index.html" ` +
      `(manifestTransforms in build-sw.mjs did not rename them): ` +
      `${leftoverIndexHtml.slice(0, 5).join(', ')}${leftoverIndexHtml.length > 5 ? ', ...' : ''}`
  );
}

// Spot-check one representative URL at every route depth/type this site
// actually serves. A clean rebuild with the underlying bug reintroduced
// would fail here even if some other check were somehow satisfied.
const expectedCleanUrls = [
  'index.html', // root - special-cased, see comment above
  'tehillim',
  'tehillim/119',
  'mishnah',
  'mishnah/berakhot',
  'mishnah/berakhot/1',
  'mishnah/by-name',
  'hazkara',
];

const missing = expectedCleanUrls.filter((url) => !urls.has(url));
if (missing.length > 0) {
  errors.push(`Expected clean-URL precache entries are missing: ${missing.join(', ')}`);
}

if (errors.length > 0) {
  console.error('dist/sw.js precache manifest verification FAILED:');
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}

console.log(`dist/sw.js precache manifest verified: ${urls.size} entries, all clean-URL (no stray "/index.html").`);
